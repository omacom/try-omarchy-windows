#!/usr/bin/env python3
"""Generates kmt_table.h: every D3DKMT function that maps 1:1 to a /dev/dxg
ioctl, with the ioctl's argument structure.

    python gen_kmt_table.py <libdxg>/src/d3dkmt-wsl.cpp > kmt_table.h

Function names and ioctl numbers come from Microsoft's libdxg (MIT); the
argument structures from the guest's uapi d3dkmthk.h, matched by number.
"""
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent
uapi = (here.parent / "guest/include/uapi/misc/d3dkmthk.h").read_text()
libdxg = pathlib.Path(sys.argv[1]).read_text()

structs = {int(nr, 16): s for nr, s in re.findall(
    r"_IOWR\(0x47,\s*(0x[0-9a-fA-F]+),\s*struct (\w+)\)", uapi)}
names = {int(nr, 16): name for name, nr in re.findall(
    r"DEFINE_KMT(?:_WITH_RETRY)?\((\w+),\s*\w+,\s*(0x[0-9a-fA-F]+)", libdxg)}
# Defined by hand in libdxg (string conversion or argument rewriting).
names[0x09] = "QueryAdapterInfo"
names[0x28] = "OpenResource"
names[0x3f] = "ShareObjectsInternal"

print("/* Generated by gen_kmt_table.py. Do not edit. */")
for nr in sorted(names):
    if nr not in structs:
        print(f"/* {names[nr]} (0x{nr:02x}): no uapi structure */")
        continue
    print(f"KMT({names[nr]}, 0x{nr:02x}, {structs[nr]})")
